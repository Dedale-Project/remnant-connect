import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const root = new URL('../plugins/remnant-agent/', import.meta.url);
const json = name => JSON.parse(readFileSync(new URL(name, root)));
const portable = json('plugin.json'), native = json('.codex-plugin/plugin.json');
assert.equal(portable.name, 'remnant-agent');
assert.equal(native.version, portable.version);
assert.deepEqual(native.interface, portable.extensions['com.openai'].interface);
const ui = native.interface;
assert.ok(ui.shortDescription.length <= 30);
assert.ok(ui.defaultPrompt.length <= 3);
assert.equal(portable.extensions['com.openai'].review.test_cases.positive.length, 5);
assert.equal(portable.extensions['com.openai'].review.test_cases.negative.length, 3);
for (const field of ['websiteURL', 'supportURL', 'privacyPolicyURL', 'termsOfServiceURL'])
  assert.equal(new URL(ui[field]).origin, 'https://remnant.dedale-bi.com');
const servers = json('mcp.json').mcpServers;
assert.deepEqual(Object.keys(servers), ['remnant-agent']);
const server = servers['remnant-agent'], auth = server.extensions['com.openai'].auth;
assert.equal(server.type, 'streamable-http');
assert.equal(server.url, 'https://remnant.dedale-bi.com/mcp/agent-connect?profile=chatgpt-v1');
assert.equal(auth.type, 'oauth');
assert.equal(auth.client.mode, 'dcr');
assert.equal(auth.resource, 'https://remnant.dedale-bi.com/mcp/agent-connect');
assert.deepEqual(auth.baseScopes, ['agent:read', 'memory:read', 'memory:write', 'memory:feedback']);
assert.deepEqual(auth.defaultScopes, []);
assert.equal(Object.hasOwn(server, 'headers'), false);
const read = JSON.parse(readFileSync(new URL('../plugins/remnant/mcp.json', import.meta.url)));
assert.ok(JSON.stringify(read).includes('/mcp/chatgpt'));
assert.ok(!JSON.stringify(read).includes('/mcp/agent'));
console.log('PASS: Agent metadata and documented OpenAI OAuth extension; Read remains separate.');
